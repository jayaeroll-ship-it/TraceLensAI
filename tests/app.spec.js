import {test,expect} from '@playwright/test';
test('desktop workflow and mobile navigation',async({page,request})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/');
 await expect(page.getByRole('heading',{name:'Project overview'})).toBeVisible();
 await expect(page.getByText('60%',{exact:true})).toBeVisible();
 await page.screenshot({path:'../artifacts/dashboard-desktop.png',fullPage:true});
 await page.getByRole('button',{name:'New project',exact:true}).click();
 await page.getByLabel('name',{exact:true}).fill('Browser QA project');
 await page.getByRole('button',{name:'Save',exact:true}).click();
 await expect(page.getByRole('dialog')).toHaveCount(0);
 await page.getByRole('button',{name:'Add requirement',exact:true}).click();
 await page.getByLabel('title',{exact:true}).fill('UI test requirement');
 await page.getByLabel('description',{exact:true}).fill('Exercise the local CRUD workflow');
 await page.getByLabel('Acceptance criteria',{exact:true}).fill('Save and retrieve the record');
 await page.getByRole('button',{name:'Save',exact:true}).click();
 await expect(page.getByRole('dialog')).toHaveCount(0);
 await page.getByRole('button',{name:'Requirements',exact:true}).click();
 await expect(page.getByText('UI test requirement',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Edit UI test requirement',exact:true}).click();
 await page.getByLabel('title',{exact:true}).fill('Edited UI requirement');
 await page.getByRole('button',{name:'Save',exact:true}).click();
 await expect(page.getByRole('dialog')).toHaveCount(0);
 await page.getByRole('button',{name:'Test cases',exact:true}).click();
 await page.getByRole('button',{name:'New test case',exact:true}).click();
 await page.getByLabel('title',{exact:true}).fill('Browser-created test');
 await page.getByLabel('steps',{exact:true}).fill('Create requirement and verify it in the list');
 await page.getByLabel('Expected result',{exact:true}).fill('Requirement visible');
 await page.getByRole('button',{name:'Save',exact:true}).click();
 await expect(page.getByRole('dialog')).toHaveCount(0);
 await page.getByRole('button',{name:'Record result',exact:true}).click();
 await page.getByRole('combobox',{name:'Result',exact:true}).selectOption('Passed');
 await page.getByLabel(/Manual execution notes/).fill('Playwright UI run: created and edited a requirement; verified it appeared in the requirements list. Local Edge.');
 await page.getByRole('button',{name:'Save',exact:true}).click();
 await expect(page.getByRole('dialog')).toHaveCount(0);
 await expect(page.locator('td .badge').filter({hasText:'Passed'})).toBeVisible();
 await page.getByLabel('Requirement for suggestions').selectOption({label:'Edited UI requirement'});
 await page.getByRole('button',{name:'Generate Test Suggestions'}).click();
 await expect(page.getByText('Basic templates · AI unavailable',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Review & save'}).first().click();
 await page.getByRole('button',{name:'Save',exact:true}).click();
 await expect(page.getByRole('dialog')).toHaveCount(0);
 await page.getByRole('button',{name:'QA report',exact:true}).click();
 const downloadPromise=page.waitForEvent('download');
 await page.getByRole('link',{name:'Export CSV'}).click();
 expect((await downloadPromise).suggestedFilename()).toBe('tracelens-report.csv');
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('button',{name:'Toggle navigation'}).click();
 await page.getByRole('button',{name:'Dashboard',exact:true}).click();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:'../artifacts/dashboard-mobile.png',fullPage:true});
 await page.getByRole('button',{name:'Toggle navigation'}).click();
 await page.getByRole('button',{name:'Requirements',exact:true}).click();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 page.on('dialog',d=>d.accept());
 await page.getByRole('button',{name:'Delete Edited UI requirement',exact:true}).click();
 await expect(page.getByText('No matching records. Add a record or adjust your filters.')).toBeVisible();
 await page.getByRole('button',{name:'Delete project',exact:true}).click();
 await expect(page.getByLabel('Project',{exact:true})).toHaveValue('1');
 await page.route('**/api/projects/1/workspace',route=>route.abort());
 await page.reload();
 await expect(page.getByRole('alert')).toContainText('Cannot reach the backend');
 expect(errors).toEqual([]);
});
